import streamlit as st
import pandas as pd
import joblib
from pathlib import Path

st.set_page_config(page_title="Credit Scoring Model", page_icon="💳", layout="centered")
st.title("💳 Credit Scoring Model")
st.write("A machine-learning demo that estimates credit application status from financial inputs.")
st.warning("Educational demonstration using a synthetic dataset. This is not a real lending decision or financial advice.")

model_path = Path(__file__).with_name("credit_model.pkl")
if not model_path.exists():
    st.info("Model file not found. Run `python train_model.py` first.")
    st.stop()
model = joblib.load(model_path)

with st.form("credit_form"):
    age = st.slider("Age", 18, 80, 30)
    income = st.number_input("Annual income (₹)", 10000, 1000000, 500000, step=10000)
    employment = st.slider("Years of employment", 0, 45, 4)
    loan = st.number_input("Requested loan amount (₹)", 1000, 1000000, 100000, step=5000)
    debt = st.number_input("Existing debt (₹)", 0, 1000000, 30000, step=5000)
    late = st.slider("Late payments in recent history", 0, 12, 1)
    history = st.slider("Credit history (years)", 0, 40, 5)
    submitted = st.form_submit_button("Predict")
if submitted:
    row = pd.DataFrame([{
        "age": age, "annual_income": income, "employment_years": employment,
        "loan_amount": loan, "existing_debt": debt, "late_payments": late,
        "credit_history_years": history
    }])
    pred = int(model.predict(row)[0])
    probability = float(model.predict_proba(row)[0][pred])
    if pred == 1:
        st.success(f"Model result: Likely approved (demo confidence: {probability:.1%})")
    else:
        st.error(f"Model result: Likely not approved (demo confidence: {probability:.1%})")
    st.caption("This result is generated by a synthetic teaching model and must not be used for actual credit decisions.")
